import java.util.Properties

// The debug builds talk to a local server (gradle.properties or -Phypertube.serverUrl), the release to the production
val debugServerUrl = (findProperty("hypertube.serverUrl") as String?)?.trimEnd('/') ?: "http://10.0.2.2:8080"
val releaseServerUrl = "https://hypertube.bajeanno.com"

// Release signing, from keystore.properties (not committed, see README): without it the release APK is unsigned
val keystore = rootProject.file("keystore.properties").takeIf { it.exists() }?.let { file ->
    Properties().apply { file.inputStream().use(::load) }
}

android {
    namespace = "com.hypertube.tv"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.hypertube.tv"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"
    }

    signingConfigs {
        if (keystore != null)
            create("release") {
                storeFile = rootProject.file(keystore.getProperty("storeFile"))
                storePassword = keystore.getProperty("storePassword")
                keyAlias = keystore.getProperty("keyAlias")
                keyPassword = keystore.getProperty("keyPassword")
            }
    }

    buildTypes {
        debug {
            buildConfigField("String", "SERVER_URL", "\"$debugServerUrl\"")
            // The local server is plain http
            manifestPlaceholders["cleartextTraffic"] = true
        }
        release {
            buildConfigField("String", "SERVER_URL", "\"$releaseServerUrl\"")
            manifestPlaceholders["cleartextTraffic"] = false
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }
}

